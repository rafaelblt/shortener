class ShortURLError(Exception):
    """Base Exception for ShortURL"""

class ShortURLDeletionNotFoundError(ShortURLError): ...

class ShortURLInactiveError(ShortURLError): ...
class ShortURLExpiredError(ShortURLError): ...

class ShortURLInvalidSlugError(ShortURLError): ...
class ShortURLSlugAlreadyExistsError(ShortURLError): ...
class ShortURLForbiddenSlugError(ShortURLError): ...
class ShortURLSlugTooLongError(ShortURLError): ...
class ShortURLSlugTooShortError(ShortURLError): ...
