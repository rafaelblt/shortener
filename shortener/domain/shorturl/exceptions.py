class ShortURLAttributeTypeError(TypeError):
    def __init__(self, attr: str, type_expected: str, got):
        super().__init__(
            f"The ShortURL {attr} must be an instance of {type_expected}, not "
            f"{type(got).__name__}"
        )


class ShortURLError(Exception):
    """Base Exception for ShortURL"""

class ShortURLDeletionNotFoundError(ShortURLError): ...


# - VALIDATION EXCEPTIONS
class ShortURLValidationError(Exception): ...
# -- Slug exceptions
class ShortURLInvalidSlugError(ShortURLValidationError): ...
class ShortURLSlugAlreadyExistsError(ShortURLValidationError): ...
class ShortURLForbiddenSlugError(ShortURLValidationError): ...
class ShortURLSlugTooLongError(ShortURLValidationError): ...
class ShortURLSlugTooShortError(ShortURLValidationError): ...
# -- URL exceptions
class ShortURLInvalidURLError(ShortURLValidationError): ...
# -- Datetime exceptions
class ShortURLInvalidDatetimeTimezone(ShortURLValidationError): ...
# -- Availability exceptions
class ShortURLInactiveError(ShortURLError): ...
class ShortURLExpiredError(ShortURLError): ...
